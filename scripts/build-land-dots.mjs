#!/usr/bin/env node
// Precomputes which points of the landing globe's Fibonacci sphere fall on land
// (Natural Earth 50m, via world-atlas) and writes them as a base64 bitmask, so
// the browser ships no geo data or point-in-polygon code. Re-run only to change
// the dot count: node scripts/build-land-dots.mjs [count]
// fibonacciPoint must stay identical to the one in src/components/landing/globe/geo.ts.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const SOURCE = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/land-50m.json";
const count = Number(process.argv[2] ?? 16000);
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "components", "landing", "globe", "landDots.ts");

const GOLDEN_ANGLE = Math.PI * (3 - Math.sqrt(5));

function fibonacciPoint(i, n) {
  const lat = (Math.asin(1 - (2 * (i + 0.5)) / n) * 180) / Math.PI;
  const lng = (((i * GOLDEN_ANGLE * 180) / Math.PI) % 360) - 180;
  return { lat, lng };
}

function decodeArcs(topology) {
  const { scale, translate } = topology.transform;
  return topology.arcs.map((arc) => {
    let x = 0;
    let y = 0;
    return arc.map(([dx, dy]) => {
      x += dx;
      y += dy;
      return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
    });
  });
}

function landRings(topology) {
  const arcs = decodeArcs(topology);
  const ring = (indexes) =>
    indexes.flatMap((index, n) => {
      const points = index < 0 ? [...arcs[~index]].reverse() : arcs[index];
      return n === 0 ? points : points.slice(1);
    });
  const rings = [];
  for (const geometry of topology.objects.land.geometries) {
    const polygons = geometry.type === "Polygon" ? [geometry.arcs] : geometry.arcs;
    for (const polygon of polygons) for (const indexes of polygon) rings.push(ring(indexes));
  }
  return rings.map((points) => {
    const lats = points.map((p) => p[1]);
    return { points, minLat: Math.min(...lats), maxLat: Math.max(...lats) };
  });
}

function isLand(rings, lng, lat) {
  let inside = false;
  for (const { points, minLat, maxLat } of rings) {
    if (lat < minLat || lat > maxLat) continue;
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [xi, yi] = points[i];
      const [xj, yj] = points[j];
      if (yi > lat !== yj > lat && lng < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

const topology = await (await fetch(SOURCE)).json();
const rings = landRings(topology);
const bits = new Uint8Array(Math.ceil(count / 8));
let land = 0;
for (let i = 0; i < count; i++) {
  const { lat, lng } = fibonacciPoint(i, count);
  if (isLand(rings, lng, lat)) {
    bits[i >> 3] |= 1 << (i & 7);
    land++;
  }
}

writeFileSync(
  out,
  `// Generated by scripts/build-land-dots.mjs from Natural Earth 50m land. Do not edit.
export const DOT_COUNT = ${count};
export const LAND_BITS =
  "${Buffer.from(bits).toString("base64")}";
`,
);
console.log(`${land} of ${count} dots on land → ${out}`);
